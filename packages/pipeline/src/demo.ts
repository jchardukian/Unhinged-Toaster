import fs from 'node:fs';
import path from 'node:path';
import { log, type Config } from './config.js';
import { extractAudio, run } from './steps/media.js';
import { transcribe } from './steps/captions.js';
import { loadTemplate, pickMusic, renderShort } from './steps/render.js';
import { synthesiseCommentary } from './steps/tts.js';
import { writeCopy } from './steps/copy.js';
import type { Candidate } from '@toaster/shared';

/**
 * End-to-end smoke test with a synthetic clip we own: builds a 9 s landscape test video whose
 * audio is a spoken line (ElevenLabs if available, else a tone), then runs copy -> TTS -> captions -> render.
 * Proves the template, captions and audio mix without touching any third-party footage.
 */
export async function runDemo(cfg: Config, flags: Record<string, string | boolean>): Promise<void> {
  const dir = path.join(cfg.workDir, 'demo');
  fs.mkdirSync(dir, { recursive: true });
  const clip = path.join(dir, 'demo_source.mp4');
  const offline = !!flags.offline;

  // 1. synthetic "footage" (we own it): moving test pattern + spoken line
  const speech = path.join(dir, 'demo_speech.mp3');
  let haveSpeech = false;
  if (!offline) haveSpeech = !!(await synthesiseCommentary(cfg, 'Okay watch this, the dog is about to steal the entire pizza off the counter. Oh no. Oh no no no.', speech));
  const audioInput = haveSpeech ? ['-i', speech] : ['-f', 'lavfi', '-i', 'sine=frequency=440:duration=9'];
  await run('ffmpeg', ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=size=1280x720:rate=30:duration=9', ...audioInput,
    '-vf', "drawtext=text='DEMO CLIP':fontsize=90:fontcolor=white:borderw=4:x=(w-text_w)/2:y=(h-text_h)/2",
    '-shortest', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', clip]);

  const cand: Candidate = {
    id: 'DEMO', source_platform: 'manual', source_id: 'demo', source_url: 'https://example.invalid/demo', media_url: null, author: 'The Unhinged Toaster', author_url: null,
    title: 'Dog steals an entire pizza off the counter while owner films', description: 'demo', category: 'funny_animals', duration_sec: 9, width: 1280, height: 720,
    published_at: null, discovered_at: new Date().toISOString(), views: null, likes: null, comments: null, shares: null, engagement_velocity: null,
    heuristic_score: null, llm_score: null, final_score: null, llm_rationale: null, safety_flags: null, phash: null, duplicate_of: null,
    rights_status: 'cleared', rights_basis: 'owned', rights_evidence: 'synthetic test pattern generated by ffmpeg', rights_notes: null, attribution_text: null,
    status: 'ready', status_reason: null, updated_at: new Date().toISOString(),
  };

  // 2. transcript + copy + VO
  const audio = await extractAudio(clip, path.join(dir, 'demo_audio.mp3'));
  const transcript = audio && haveSpeech && !offline ? await transcribe(cfg, audio) : null;
  log.info(`transcript: ${transcript ? `${transcript.words.length} words: "${transcript.text}"` : 'none'}`);
  const copy = offline
    ? { headline: 'THIS DOG HAS NO CHILL', commentary: 'That pizza never stood a chance and honestly neither did the owner.', caption: 'demo', hashtags: ['funny'] }
    : await writeCopy(cfg, cand, transcript?.text);
  log.info(`copy: headline="${copy.headline}" commentary="${copy.commentary}"`);
  const vo = offline ? null : await synthesiseCommentary(cfg, copy.commentary, path.join(dir, 'demo_vo.mp3'));

  // 3. render
  const t = loadTemplate(cfg);
  const out = path.join(dir, 'demo_final.mp4');
  const r = await renderShort(cfg, t, { clipPath: clip, headline: copy.headline, commentary: copy.commentary, voPath: vo, words: transcript?.words ?? null, musicPath: pickMusic(cfg, 'funny_animals'), outPath: out, workDir: dir });
  log.info(`demo rendered: ${r.outPath} (${r.durationSec.toFixed(2)}s) thumbnail ${r.thumbnailPath}`);
  fs.writeFileSync(path.join(dir, 'demo_copy.json'), JSON.stringify({ copy, transcript: transcript?.text ?? null, vo: !!vo }, null, 2));
}

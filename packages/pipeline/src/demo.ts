import fs from 'node:fs';
import path from 'node:path';
import { log, type Config } from './config.js';
import { extractAudio, run } from './steps/media.js';
import { transcribe } from './steps/captions.js';
import { loadTemplate, pickMusic, renderShort } from './steps/render.js';
import { synthesiseCommentary } from './steps/tts.js';
import { writeCopy } from './steps/copy.js';
import { analyzeClip } from './steps/analyze.js';
import { planEdit, qualityTier, type Candidate } from '@toaster/shared';

/**
 * End-to-end smoke test with a synthetic clip we own: builds a 9 s landscape test video whose
 * audio is a spoken line (ElevenLabs if available, else a tone), then runs copy -> TTS -> captions -> render.
 * Proves the template, captions and audio mix without touching any third-party footage.
 */
export async function runDemo(cfg: Config, flags: Record<string, string | boolean>): Promise<void> {
  const dir = path.join(cfg.workDir, 'demo');
  fs.mkdirSync(dir, { recursive: true });
  const clip = path.join(dir, 'demo_source.mp4');
  const offline = !!flags.offline;

  // 1. synthetic "footage" (we own it): moving test pattern + spoken line
  const speech = path.join(dir, 'demo_speech.mp3');
  let haveSpeech = false;
  const realClip = typeof flags.clip === 'string' ? path.resolve(String(flags.clip)) : null;
  if (realClip) {
    fs.copyFileSync(realClip, clip);
  } else {
    if (!offline) haveSpeech = !!(await synthesiseCommentary(cfg, 'Okay watch this, the dog is about to steal the entire pizza off the counter. Oh no. Oh no no no.', speech));
    const audioInput = haveSpeech ? ['-i', speech] : ['-f', 'lavfi', '-i', 'sine=frequency=440:duration=9'];
    const size = flags.vertical ? '720x1280' : '1280x720';
    await run('ffmpeg', ['-y', '-v', 'error', '-f', 'lavfi', '-i', `testsrc2=size=${size}:rate=30:duration=9`, ...audioInput,
      '-vf', "drawtext=text='DEMO CLIP':fontsize=90:fontcolor=white:borderw=4:x=(w-text_w)/2:y=(h-text_h)/2",
      '-shortest', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', clip]);
  }
  const title = typeof flags.title === 'string' ? String(flags.title) : 'Dog steals an entire pizza off the counter while owner films';

  const cand: Candidate = {
    id: 'DEMO', source_platform: 'manual', source_id: 'demo', source_url: 'https://example.invalid/demo', media_url: null, author: 'The Unhinged Toaster', author_url: null,
    title, description: typeof flags.description === 'string' ? String(flags.description) : 'demo', category: 'funny_animals', duration_sec: 9, width: 1280, height: 720,
    published_at: null, discovered_at: new Date().toISOString(), views: null, likes: null, comments: null, shares: null, engagement_velocity: null,
    heuristic_score: null, llm_score: null, final_score: null, llm_rationale: null, safety_flags: null, phash: null, duplicate_of: null,
    rights_status: 'cleared', rights_basis: 'owned', rights_evidence: 'synthetic test pattern generated by ffmpeg', rights_notes: null, attribution_text: null,
    status: 'ready', status_reason: null, updated_at: new Date().toISOString(), copyright_risk: null, copyright_risk_reasons: null,
  };

  // 2. transcript + copy + VO
  const audio = await extractAudio(clip, path.join(dir, 'demo_audio.mp3'));
  const transcript = audio && (haveSpeech || !!realClip) && !offline ? await transcribe(cfg, audio) : null;
  log.info(`transcript: ${transcript ? `${transcript.words.length} words: "${transcript.text}"` : 'none'}`);
  const copy = offline
    ? { headline: 'THIS DOG HAS NO CHILL', commentary: 'That pizza never stood a chance and honestly neither did the owner.', caption: 'demo', hashtags: ['funny'], sticker: 'NOPE.', freeze_text: 'WAIT FOR IT…', edit_style: 'full' as const }
    : await writeCopy(cfg, cand, transcript?.text);
  log.info(`copy: headline="${copy.headline}" commentary="${copy.commentary}"`);
  const vo = offline ? null : await synthesiseCommentary(cfg, copy.commentary, path.join(dir, 'demo_vo.mp3'));

  // 3. clip-specific edit plan from signal analysis + director fields
  const t = loadTemplate(cfg);
  const analysis = await analyzeClip(clip);
  const probeQ = await (await import('./steps/media.js')).ffprobe(clip);
  const tier = qualityTier(probeQ.width, probeQ.height);
  log.info(`source ${probeQ.width}x${probeQ.height} -> quality tier ${tier}${tier === 'low' ? ' (the production pipeline REJECTS this; demo continues)' : tier === 'ok' ? ' (used only when 1080p stock runs out)' : ''}`);
  const outroReserve = t.commentary.position === 'intro' ? 0 : t.commentary.outroSeconds + 1.5;
  const timeline = planEdit({
    sourceDuration: Math.min(analysis.duration, t.limits.maxDurationSec - outroReserve), peak: analysis.peak?.t ?? null,
    maxTotal: t.limits.maxDurationSec - outroReserve, style: copy.edit_style ?? 'full', stickerText: copy.sticker ?? null, freezeText: copy.freeze_text ?? null,
    hasSpeech: realClip ? (transcript?.words.length ?? 0) >= 6 : false, // synthetic demo forces the full beat set
  });
  if (flags.commentary === 'none') { /* no outro: the planner already got maxTotal with outro included; fine for a 9 s demo */ }
  log.info(`edit plan: ${JSON.stringify(timeline.beats)} dropped=${timeline.dropped.join(',') || 'none'}`);

  // 4. render
  const out = path.join(dir, 'demo_final.mp4');
  const commentaryMode = (['outro_voice', 'text_only', 'none'].includes(String(flags.commentary)) ? String(flags.commentary) : copy.commentary_mode ?? 'outro_voice') as 'outro_voice' | 'text_only' | 'none';
  const r = await renderShort(cfg, t, { clipPath: clip, headline: copy.headline, commentary: copy.commentary, commentaryMode, voPath: vo, words: transcript?.words ?? null, musicPath: pickMusic(cfg, 'funny_animals'), outPath: out, workDir: dir, timeline });
  log.info(`demo rendered: ${r.outPath} (${r.durationSec.toFixed(2)}s, edited clip ${r.editedClipSec}s) thumbnail ${r.thumbnailPath}`);
  fs.writeFileSync(path.join(dir, 'demo_copy.json'), JSON.stringify({ copy, transcript: transcript?.text ?? null, vo: !!vo, peak: analysis.peak, beats: timeline.beats, dropped: timeline.dropped }, null, 2));
}
